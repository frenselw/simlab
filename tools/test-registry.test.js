'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {tests,info,validateRegistry,helpers}=require('./test-registry');
const {selectAffected}=require('./test-selection');
const parent=path.resolve(__dirname,'../output/ci-tests');fs.mkdirSync(parent,{recursive:true});
const directory=fs.mkdtempSync(path.join(parent,'registry-fixture-'));
const write=(file,text='')=>{const target=path.join(directory,file);fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,text);};
try{
 write('sim/new-lab/main.js');write('sim/new-lab/model.test.js');
 write('tools/new-lab-browser-regression.js',"require('./new-lab-browser-cases');");
 write('tools/new-lab-browser-cases.js');
 const browser={file:'tools/new-lab-browser-regression.js',kind:'browser',scope:'new-lab'};
 const entries=['sim/new-lab/model.test.js',browser];
 const helper={file:'tools/new-lab-browser-cases.js',scope:'new-lab',consumers:[browser.file]};
 const options={entries,helperEntries:[helper],manualEntries:[],lists:[],directory};
 assert.equal(validateRegistry(options).browser,1,'a new activity registers without modifying historical evidence');
 assert.throws(()=>validateRegistry({...options,entries:entries.slice(0,1)}),/Unmapped browser helper consumer/);
 assert.throws(()=>validateRegistry({...options,entries:[entries[0],{file:browser.file}]}),/Invalid test scope/);
 assert.throws(()=>validateRegistry({...options,entries:[entries[0],{file:browser.file,scope:'new-lab'}]}),/Invalid test kind/);
 assert.throws(()=>validateRegistry({...options,entries:[entries[0],{...browser,scope:'typo-lab'}]}),/Invalid test scope/);
 assert.throws(()=>validateRegistry({...options,entries:[...entries,browser]}),/Duplicate registered/);
 assert.throws(()=>validateRegistry({...options,helperEntries:[]}),/Unregistered browser helper import/);
 assert.throws(()=>validateRegistry({...options,helperEntries:[{...helper,consumers:[]}]}),/requires consumers/);
 write('tools/second-browser-regression.js',"require('./new-lab-browser-cases');");
 const second={file:'tools/second-browser-regression.js',kind:'browser',scope:'new-lab'};
 assert.throws(()=>validateRegistry({...options,entries:[...entries,second]}),/Unregistered browser helper import/,'another driver must declare its use of an existing helper');
 validateRegistry({...options,entries:[...entries,second],helperEntries:[{...helper,consumers:[browser.file,second.file]}]});
 fs.unlinkSync(path.join(directory,second.file));
 assert.throws(()=>validateRegistry({...options,entries:[browser],helperEntries:[helper,{file:entries[0],scope:'new-lab',consumers:[browser.file]}]}),/Invalid browser helper filename/,'logical tests cannot be hidden as helper modules');
 write(browser.file,'');
 assert.throws(()=>validateRegistry(options),/not imported/);write(browser.file,"require('./new-lab-browser-cases');");
 write('tools/forgotten-browser-regression.js');
 assert.throws(()=>validateRegistry(options),/Unregistered test: tools\/forgotten-browser-regression.js/);
 const manual={file:'tools/forgotten-browser-regression.js',scope:'new-lab',reason:'Separate deployment host matrix'};
 validateRegistry({...options,manualEntries:[manual]});
 assert.throws(()=>validateRegistry({...options,manualEntries:[{...manual,reason:''}]}),/requires a reason/);
 assert.throws(()=>validateRegistry({...options,manualEntries:[{...manual,file:browser.file}]}),/Duplicate test classification/);
 assert.throws(()=>validateRegistry({...options,entries:[browser],manualEntries:[{file:entries[0],scope:'new-lab',reason:'Excluded'}]}),/requires a reason/,'logical tests cannot be hidden as manual browser gates');
 fs.unlinkSync(path.join(directory,manual.file));
 write('tools/custom-check.js');write('package.json',JSON.stringify({scripts:{'test:browser:new':'node tools/custom-check.js'}}));
 assert.throws(()=>validateRegistry(options),/Unregistered test: tools\/custom-check.js/);
 write('package.json','{}');write('sim/new-lab/forgotten.test.js');
 assert.throws(()=>validateRegistry(options),/Unregistered test: sim\/new-lab\/forgotten.test.js/);
 fs.unlinkSync(path.join(directory,'sim/new-lab/forgotten.test.js'));
 write('sim/new-lab/assets.json',JSON.stringify({files:['new-lab/main.js']}));
 const list={file:'sim/new-lab/assets.json',scope:'new-lab'};
 validateRegistry({...options,lists:[list]});
 assert.throws(()=>validateRegistry({...options,lists:[list,list]}),/Duplicate runtime asset list/);
 write(list.file,JSON.stringify({files:[]}));assert.throws(()=>validateRegistry({...options,lists:[list]}),/Empty runtime asset list/);
 write(list.file,JSON.stringify({files:['../outside.js']}));assert.throws(()=>validateRegistry({...options,lists:[list]}),/Invalid registry file/);
 const node=entries[0],other={file:'tools/other-browser-regression.js',kind:'browser',scope:'other-lab'};
 const selected=selectAffected([node,browser,other],['sim/new-lab/main.js'],{assets:new Map([['sim/new-lab/main.js',new Set(['new-lab'])]])});
 assert.equal(selected.mode,'affected');
 assert.deepEqual(selected.entries.map(e=>e.file),[node,browser.file],'new activity selects its own browser and the fast layer');
 assert.equal(selectAffected(tests,['tools/test-registry.js']).mode,'full');
 assert.equal(selectAffected(tests,['tools/circuit-energy-r2-browser-cases.js']).mode,'affected','transitive helper has a current owner');
 for(const entry of tests.filter(t=>info(t).kind==='browser'))assert(info(entry).scope!=='tools');
 assert(helpers.every(e=>e.consumers.length));
}finally{
 assert.equal(path.dirname(directory),parent);assert(path.basename(directory).startsWith('registry-fixture-'));
 fs.rmSync(directory,{recursive:true,force:true});
}
console.log('Registry detects missing entries, ownership, helper imports and manual reasons; new activity selection stays scoped.');
