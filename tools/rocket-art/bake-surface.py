"""Bake the shared illustrative collision field without rebuilding terrain meshes."""
from pathlib import Path
import base64, gzip, hashlib, importlib.util, json, struct
import numpy as np
from PIL import Image, ImageDraw
from scipy.ndimage import distance_transform_edt, map_coordinates

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('global_terrain', HERE / 'global-terrain.py')
globe = importlib.util.module_from_spec(spec)
spec.loader.exec_module(globe)
ROOT = HERE.parents[1]
WIDTH, HEIGHT, LOCAL_SIZE = 721, 361, 257
LAND, HEIGHT_MASK = 32768, 32767


def packed(heights, land):
    assert np.isfinite(heights).all() and np.min(heights) >= 0 and np.max(heights) <= 3500
    value = np.rint(heights).astype('<u2')
    value[~land] = 0
    value[land] |= LAND
    assert np.all((value[~land] & HEIGHT_MASK) == 0)
    return value


def main():
    image = Image.new('L', (3601, 1801))
    draw = ImageDraw.Draw(image)
    rings = [ring for shape in globe.art.load_shapes('ne_50m_land') for ring in shape]
    for outer in (True, False):
        for ring in rings:
            if (globe.area(ring) < 0) == outer:
                draw.polygon([((lon + 180) * 10, (90 - lat) * 10) for lon, lat in ring], fill=255 if outer else 0)
    raster = np.asarray(image) > 127
    # Natural Earth closes Antarctica at -89.9989 degrees; extend its numerical cap.
    assert any(np.min(ring[:, 1]) < -89.99 for ring in rings)
    raster[-1, :] = raster[-2, :]
    shore = distance_transform_edt(raster) * 11.12
    lon, lat = np.meshgrid(np.linspace(-180, 180, WIDTH), np.linspace(90, -90, HEIGHT))
    points = np.column_stack((lon.ravel(), lat.ravel()))
    coordinates = [(90 - points[:, 1]) * 10, (points[:, 0] + 180) * 10]
    land = map_coordinates(raster.astype('u1'), coordinates, order=0, mode='nearest').reshape(HEIGHT, WIDTH).astype(bool)
    distance = map_coordinates(shore, coordinates, order=1, mode='nearest')
    heights = globe.field(points, distance)[0].reshape(HEIGHT, WIDTH)
    values = packed(heights, land)
    # One longitude-independent value at each pole, and identical antimeridian samples.
    values[0, :] = values[0, WIDTH // 2]
    values[-1, :] = values[-1, WIDTH // 2]
    values[:, -1] = values[:, 0]
    assert np.all(values[:, -1] == values[:, 0])
    assert np.all(values[0] == values[0, 0]) and np.all(values[-1] == values[-1, 0])
    assert values[0, 0] == 0 and values[-1, 0] & LAND, 'North ocean / Antarctic land poles'

    binary = (ROOT / 'sim/rocket-space-mission-lab/assets/terrain.bin').read_bytes()
    length = struct.unpack_from('<I', binary)[0]
    header = json.loads(binary[4:4 + length])
    assert header['heightSize'] == LOCAL_SIZE and header['extent'] == 240000
    start = 4 + (length + 3) // 4 * 4
    local_heights = np.frombuffer(binary, '<f4', LOCAL_SIZE ** 2, start).reshape(LOCAL_SIZE, LOCAL_SIZE).copy()
    source = json.loads((ROOT / 'output/rocket/terrain-source.json').read_text(encoding='utf-8'))
    local_land = np.asarray(source['shore']) > 0
    assert local_land.shape == local_heights.shape
    mid = LOCAL_SIZE // 2
    local_land[mid, mid] = True
    local_values = packed(local_heights, local_land)
    assert local_values[mid, mid] == LAND, 'Launch surface is land at zero elevation'
    data = dict(version=1, width=WIDTH, height=HEIGHT, global_=base64.b64encode(values.tobytes()).decode(), localSize=LOCAL_SIZE, extent=240000, local=base64.b64encode(local_values.tobytes()).decode(), maxHeight=3500)
    data['global'] = data.pop('global_')
    text = "/* Generated by tools/rocket-art/bake-surface.py; illustrative terrain in metres. */\n(function(root){const data=" + json.dumps(data, separators=(',', ':')) + ";if(typeof module==='object'&&module.exports)module.exports=data;else root.RocketSurfaceData=data;})(typeof globalThis!=='undefined'?globalThis:this);\n"
    output = ROOT / 'sim/rocket-space-mission-lab/surface-data.js'
    output.write_text(text, encoding='utf-8', newline='\n')
    contents = output.read_bytes()
    assert len(contents) < 1000000
    metadata = dict(version=1, file='surface-data.js', width=WIDTH, height=HEIGHT, localSize=LOCAL_SIZE, extent=240000, bytes=len(contents), gzipBytes=len(gzip.compress(contents, mtime=0)), sha256=hashlib.sha256(contents).hexdigest(), landSamples=int(np.count_nonzero(values & LAND)), globalMaxHeight=int(np.max(values & HEIGHT_MASK)), localMaxHeight=int(np.max(local_values & HEIGHT_MASK)), terrainSha256=hashlib.sha256(binary).hexdigest(), sourceSha256=hashlib.sha256((HERE / 'sources/ne_50m_land.zip').read_bytes()).hexdigest())
    (ROOT / 'output/rocket/surface-metadata.json').write_text(json.dumps(metadata, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(metadata))


if __name__ == '__main__':
    main()
