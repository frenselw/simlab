'use strict';
const assert = require('node:assert/strict');
const {cases,groups,createCoverage,parseCircuitSelection}=require('./circuit-test-groups');
const split=groups.flatMap(g=>createCoverage(g,['source','package']).entries.map(e=>e.id));
const full=createCoverage(null,['source','package']).entries.map(e=>e.id);
assert.equal(new Set(split).size,split.length);
assert.deepEqual(split.sort(),full.sort(),'four groups exactly partition every declared legacy case/mode');
assert(Object.hasOwn(cases,'host-ownership')&&Object.hasOwn(cases,'fullscreen-policy'),'the legacy tail remains mandatory');
const c=createCoverage('hosts',['source']);
assert.equal(c.begin('source','startup'),false);
assert.throws(()=>c.finish(),/incomplete/);
assert(c.begin('source','host-ownership'));
c.end('source','host-ownership');
assert.throws(()=>c.begin('source','host-ownership'),/twice/);
assert(c.begin('source','fullscreen-policy'));
c.end('source','fullscreen-policy');c.finish();
assert.throws(()=>createCoverage('unknown',['source']),/Unknown/);
assert.equal(parseCircuitSelection(['--entry=source','--group=hosts']).fullRun,true);
assert.equal(parseCircuitSelection(['--entry=source','--platform-core-smoke']).fullRun,false);
for(const args of [['--group='],['--group=unknown'],['--entry=bad'],['--group=hosts','--group=editing'],['--group=hosts','--interruption-smoke']])assert.throws(()=>parseCircuitSelection(args));
console.log('DC groups partition all cases/modes and reject incomplete or duplicate coverage.');
